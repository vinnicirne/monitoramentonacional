// Helper: Encontrar delegacia por nome de bairro
export function findDelegaciaByBairro(bairroQuery: string, ufFilter?: 'MG' | 'ES'): DelegaciaTerritorialMgEs[] {
  const q = bairroQuery.trim().toLowerCase();
  if (!q) return [];
  return DELEGACIAS_MG_ES_DATA.filter(d => {
    if (ufFilter && d.uf !== ufFilter) return false;
    return d.bairros.some(b => b.toLowerCase().includes(q)) || d.municipio.toLowerCase().includes(q);
  });
}
